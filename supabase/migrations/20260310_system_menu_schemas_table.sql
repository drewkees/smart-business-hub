-- System menu configuration table for System Owner

create table if not exists public.schemas (
  itemid bigint generated by default as identity primary key,
  menuid text not null,
  menuname text not null,
  menucmd text,
  objectcode text,
  menutype text not null default 'P' check (menutype in ('M', 'S', 'P')),
  menuicon text,
  udfmaintained boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists schemas_menuid_idx on public.schemas(menuid);
create index if not exists schemas_menutype_idx on public.schemas(menutype);

drop trigger if exists set_schemas_updated_at on public.schemas;
create trigger set_schemas_updated_at
before update on public.schemas
for each row execute procedure public.set_updated_at();

alter table public.schemas enable row level security;

drop policy if exists "schemas_select_superadmin" on public.schemas;
create policy "schemas_select_superadmin"
on public.schemas for select
to authenticated
using (public.is_superadmin(auth.uid()));

drop policy if exists "schemas_insert_superadmin" on public.schemas;
create policy "schemas_insert_superadmin"
on public.schemas for insert
to authenticated
with check (public.is_superadmin(auth.uid()));

drop policy if exists "schemas_update_superadmin" on public.schemas;
create policy "schemas_update_superadmin"
on public.schemas for update
to authenticated
using (public.is_superadmin(auth.uid()))
with check (public.is_superadmin(auth.uid()));

drop policy if exists "schemas_delete_superadmin" on public.schemas;
create policy "schemas_delete_superadmin"
on public.schemas for delete
to authenticated
using (public.is_superadmin(auth.uid()));
